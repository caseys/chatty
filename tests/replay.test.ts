import { describe, expect, it, afterAll } from 'vitest';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'acorn';
import { inspectExecutableCode } from '../src/tools/javascript-runtime.ts';
import { renameMembers, unknownMembers } from '../src/core/property-check.ts';
import { errorHint } from '../src/core/error-hints.ts';

interface Case { id: string; reply?: string; program?: string; error?: string; errorLine?: number }
const cases: Case[] = JSON.parse(readFileSync(join(process.cwd(), 'tests/replay/cases.json'), 'utf8'));

function parses(code: string): boolean {
  try {
    parse(code, { ecmaVersion: 'latest', allowAwaitOutsideFunction: true, allowReturnOutsideFunction: true });
    return true;
  } catch {
    return false;
  }
}

/** Short stable name for a correction note: the text before any quoted detail */
const kindOf = (note: string) => note.split(/[:(]/)[0].replace(/[`'"][^`'"]*[`'"]/g, '…').trim().slice(0, 60);

const fired = new Map<string, string[]>();
const record = (id: string, repair: string) => fired.set(id, [...(fired.get(id) ?? []), repair]);

describe('replay of real failures (offline, no model)', () => {
  for (const c of cases) {
    it(c.id, () => {
      fired.set(c.id, []);
      if (c.reply !== undefined) {
        const prepared = inspectExecutableCode(c.reply);
        if (!prepared.isProse) {
          expect(prepared.code.trim(), 'inspectExecutableCode returned no code').not.toBe('');
          if (prepared.code !== c.reply.trim()) {
            record(c.id, 'inspect: reply rewritten');
            expect(prepared.code).not.toBe(c.reply);
            // The rewrite of a reply can still hold the model's own mistakes (e.g. await in a plain
            // function inside an inline <script>): flagged in the report, not a failure of the repair
            if (!parses(prepared.code)) record(c.id, 'FLAG inspect output does not parse');
          }
        } else if (/```|\bdocument\.|\bspeak\(/.test(c.reply)) {
          expect(prepared.code.trim(), 'reply with code treated as prose with no code').not.toBe('');
        }
      }
      if (c.program !== undefined) {
        const unknown = unknownMembers(c.program);
        const slips = unknown.filter((u) => u.slip);
        if (slips.length) {
          record(c.id, 'member slip');
          const fixed = renameMembers(c.program, slips.map((u) => ({ object: u.object, from: u.member, to: u.slip! })));
          expect(fixed).not.toBe(c.program);
          if (parses(c.program)) expect(parses(fixed)).toBe(true);
        }
        if (unknown.length > slips.length) record(c.id, 'unknown member reported');
        if (c.error !== undefined) {
          const hint = errorHint(c.program, c.error, c.errorLine);
          if (hint?.correction) {
            record(c.id, `hint correction: ${kindOf(hint.correction.note)}`);
            expect(hint.correction.code).not.toBe(c.program);
            if (parses(c.program)) expect(parses(hint.correction.code), 'correction must parse').toBe(true);
          } else if (hint?.text) record(c.id, 'hint text (facts for the model)');
        }
      }
    });
  }

  afterAll(() => {
    if (!process.env.REPLAY_REPORT) return;
    const totals = new Map<string, number>();
    for (const list of fired.values()) for (const r of new Set(list)) totals.set(r, (totals.get(r) ?? 0) + 1);
    const none = cases.filter((c) => !(fired.get(c.id)?.length));
    const withError = cases.filter((c) => c.error !== undefined);
    const md = [
      '# Replay report',
      '',
      '_Generated by `npm run replay` (REPLAY_REPORT=1 vitest run tests/replay.test.ts)._',
      '',
      '**Adding cases:** in a chat, use the run log\'s "copy" link to copy its log, paste it into a file under `tests/replay/logs/` (any name), then run `node tests/replay/extract.mjs` (merges new cases into `cases.json`; also accepts Claude Code `.jsonl` transcripts as arguments), then `npm run replay`.',
      '',
      `Cases: ${cases.length} (${withError.length} with an error, ${cases.filter((c) => c.reply !== undefined).length} with a reply)`,
      '',
      '## Totals per repair (cases it fired on)',
      '',
      ...(totals.size ? [...totals].sort((a, b) => b[1] - a[1]).map(([k, n]) => `- ${k}: ${n}`) : ['- none']),
      `- no repair fired: ${none.length}`,
      '',
      '## Per case',
      '',
      '| case | error | repairs |',
      '| --- | --- | --- |',
      ...cases.map((c) => `| ${c.id} | ${c.error ? `line ${c.errorLine ?? '?'}: ${c.error.replace(/\|/g, '\\|').slice(0, 70)}` : ''} | ${[...new Set(fired.get(c.id) ?? [])].join('; ') || 'none'} |`),
      '',
      '## Cases with no help',
      '',
      ...(none.length ? none.map((c) => `- ${c.id}${c.error ? ` (${c.error.slice(0, 70)})` : ''}`) : ['- none']),
      '',
    ].join('\n');
    writeFileSync(join(process.cwd(), 'tests/replay/report.md'), md);
  });
});
